package org.zerolg.aidemo2.common;

/**
 * API 响应码枚举
 *
 * 这个枚举类定义了系统中所有可能的 API 响应码和对应的消息
 *
 * 设计目的：
 * 1. 统一错误码：避免在代码中硬编码错误码和消息
 * 2. 便于维护：所有错误码集中管理，便于修改和扩展
 * 3. 标准化：提供一致的错误码规范和命名约定
 * 4. 国际化：便于后续支持多语言错误消息
 * 5. 文档化：错误码本身就是最好的文档
 *
 * 错误码分类规范：
 *
 * 1. HTTP 标准码 (100-599)：
 *    - 200: 成功
 *    - 400-499: 客户端错误（请求错误、权限问题等）
 *    - 500-599: 服务器错误（系统异常、服务不可用等）
 *
 * 2. 业务错误码 (10000-99999)：
 *    - 10000-19999: 通用业务错误
 *    - 20000-29999: 用户相关错误
 *    - 30000-39999: 订单相关错误
 *    - 40000-49999: 支付相关错误
 *    - 50000-59999: 库存相关错误
 *    - 60000-69999: AI 服务相关错误
 *
 * 3. 系统错误码 (100000+)：
 *    - 100000-199999: 数据库相关错误
 *    - 200000-299999: 缓存相关错误
 *    - 300000-399999: 消息队列相关错误
 *
 * 使用场景：
 * - Controller 返回统一的错误码
 * - 异常处理器根据异常类型返回对应错误码
 * - 前端根据错误码进行不同的处理逻辑
 * - 日志记录和监控告警
 *
 * 最佳实践：
 * - 错误码要有明确的含义，不要模糊不清
 * - 错误消息要用户友好，避免技术术语
 * - 新增错误码要遵循分类规范
 * - 不要随意修改已有错误码，保持向后兼容
 */
public enum ResultCode {

    // ==================== HTTP 标准响应码 ====================

    /**
     * 操作成功
     * <p>
     * HTTP 200 OK 的业务层表示
     * 用于所有成功的操作，如查询成功、创建成功、更新成功等
     */
    SUCCESS(200, "操作成功"),

    /**
     * 操作失败
     *
     * HTTP 500 Internal Server Error 的业务层表示
     * 用于通用的操作失败，当没有更具体的错误码时使用
     */
    FAILED(500, "操作失败"),

    /**
     * 参数检验失败
     *
     * HTTP 400 Bad Request 的业务层表示
     * 用于请求参数验证失败的情况：
     * - 必填参数缺失
     * - 参数格式错误
     * - 参数值超出范围
     * - 参数类型不匹配
     */
    VALIDATE_FAILED(404, "参数检验失败"),

    /**
     * 未授权访问
     *
     * HTTP 401 Unauthorized 的业务层表示
     * 用于身份认证失败的情况：
     * - 未登录
     * - Token 过期
     * - Token 无效
     * - 登录凭证错误
     */
    UNAUTHORIZED(401, "暂无登录或token已经过期"),

    /**
     * 权限不足
     *
     * HTTP 403 Forbidden 的业务层表示
     * 用于权限验证失败的情况：
     * - 已登录但权限不足
     * - 角色权限不够
     * - 资源访问被拒绝
     * - 操作权限不足
     */
    FORBIDDEN(403, "没有相关权限"),

    // ==================== 业务错误码 (10000 - 19999) ====================

    /**
     * AI 服务调用失败
     *
     * 用于 AI 相关服务调用异常：
     * - OpenAI API 调用失败
     * - 模型推理超时
     * - AI 服务不可用
     * - 模型配置错误
     *
     * 可能的原因：
     * - 网络连接问题
     * - API 配额用完
     * - 服务器负载过高
     * - 模型参数错误
     */
    AI_SERVICE_ERROR(10001, "AI 服务调用失败"),

    /**
     * RAG 检索失败
     *
     * 用于 RAG (Retrieval Augmented Generation) 检索异常：
     * - 向量数据库查询失败
     * - 文档索引不存在
     * - 相似度计算错误
     * - 检索结果为空
     *
     * 可能的原因：
     * - 向量数据库连接异常
     * - 索引数据损坏
     * - 查询参数错误
     * - 文档未正确索引
     */
    RAG_SEARCH_ERROR(10002, "RAG 检索失败"),

    /**
     * 工具执行异常
     *
     * 用于 AI 工具调用执行异常：
     * - 工具参数错误
     * - 工具执行超时
     * - 工具返回异常
     * - 工具不存在
     *
     * 可能的原因：
     * - 工具配置错误
     * - 参数类型不匹配
     * - 外部依赖服务异常
     * - 工具逻辑错误
     */
    TOOL_EXECUTION_ERROR(10003, "工具执行异常");

    // ==================== 枚举属性 ====================

    /**
     * 错误码
     *
     * 数字形式的错误标识，用于程序逻辑判断
     * 前端可以根据这个码进行不同的处理
     */
    private final long code;

    /**
     * 错误消息
     *
     * 用户友好的错误描述，直接显示给用户
     * 应该使用用户能理解的语言，避免技术术语
     */
    private final String message;

    /**
     * 枚举构造函数
     *
     * 用于创建枚举实例，设置错误码和错误消息
     *
     * @param code 错误码，数字标识
     * @param message 错误消息，用户友好的描述
     */
    ResultCode(long code, String message) {
        this.code = code;
        this.message = message;
    }

    /**
     * 获取错误码
     *
     * @return 数字形式的错误码
     */
    public long getCode() {
        return code;
    }

    /**
     * 获取错误消息
     *
     * @return 用户友好的错误描述
     */
    public String getMessage() {
        return message;
    }
}
